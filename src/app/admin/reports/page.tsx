'use client'

import { Suspense, useEffect, useState } from 'react'
import { Download } from 'lucide-react'
import { isAdmin, useMe } from '@/features/auth/api'
import { useCreateExport, useExports, useReport, useReports } from '@/features/reports/api'
import { Button, EmptyState, ErrorState, fmtAgo, fmtDate, JobBadge, PageHeader, Panel, Select, Skeleton, Tabs } from '@/components/ui'
import { Markdown } from '@/components/ui/Markdown'
import { DataTable } from '@/components/ui/DataTable'
import s from '@/components/platform/page.module.scss'

const KIND_LABEL: Record<string, string> = { research_report: 'Research report', comparison_report: 'Comparative analysis', knowledge_base_index: 'Knowledge-base index', crawl_report: 'Crawl coverage', data_quality: 'Data quality' }
const ORDER = ['research_report', 'comparison_report', 'crawl_report', 'data_quality', 'knowledge_base_index']

function ReportsInner() {
  const { data: me } = useMe()
  const reports = useReports()
  const list = [...(reports.data?.data ?? [])].sort((a, b) => ORDER.indexOf(a.kind) - ORDER.indexOf(b.kind))
  const [sel, setSel] = useState<string | null>(null)
  useEffect(() => { if (!sel && list[0]) setSel(list[0].id) }, [list, sel])
  const rep = useReport(sel)
  const canExport = isAdmin(me)
  return (
    <>
      <PageHeader title="Research reports & exports" description="Reports are generated by every knowledge-base build from the canonical dataset. Exports run asynchronously in workers and are downloaded through an authorized endpoint." />
      {canExport && <ExportsPanel />}
      <Panel title="Reports" actions={reports.data && <span className={s.muted} style={{ fontSize: '0.78rem' }}>latest of each kind</span>}>
        {reports.error ? <ErrorState error={reports.error} /> : list.length === 0 && !reports.isLoading ? <EmptyState title="No reports yet">Run a knowledge-base build (Crawl jobs → Rebuild).</EmptyState> : (
          <>
            <div style={{ padding: 12 }}>
              <Tabs value={sel ?? ''} onChange={setSel} tabs={list.map((r) => ({ value: r.id, label: KIND_LABEL[r.kind] ?? r.title }))} />
            </div>
            <div className={s.pad}>
              {rep.isLoading || !rep.data ? <Skeleton h={400} /> : (
                <>
                  <p className={s.muted} style={{ fontSize: '0.78rem', marginBottom: 12 }}>Generated {fmtDate(rep.data.created_at)} · build job <span className={s.mono}>{rep.data.job_id?.slice(0, 8)}</span></p>
                  {['crawl_report', 'data_quality'].includes(rep.data.kind) ? <pre className={s.code} style={{ maxHeight: 640 }}>{JSON.stringify(rep.data.data, null, 2)}</pre> : <Markdown>{rep.data.content_md}</Markdown>}
                </>
              )}
            </div>
          </>
        )}
      </Panel>
    </>
  )
}

function ExportsPanel() {
  const exportsQ = useExports(true)
  const create = useCreateExport()
  const [format, setFormat] = useState('csv')
  const [resource, setResource] = useState('components')
  return (
    <Panel title="Exports" className="" id="exports">
      <div className={s.filters} style={{ padding: '12px 12px 0' }}>
        <Select label="Resource" value={resource} onChange={setResource} options={['all', 'systems', 'components', 'tokens', 'guidelines', 'sources'].map((x) => ({ value: x, label: x === 'all' ? 'All resources' : x }))} />
        <Select label="Format" value={format} onChange={setFormat} options={[{ value: 'csv', label: 'CSV' }, { value: 'jsonl', label: 'JSONL' }, { value: 'json', label: 'JSON' }, { value: 'xlsx', label: 'Spreadsheet (XLSX)' }, { value: 'markdown', label: 'Markdown reports' }, { value: 'bundle', label: 'Full bundle (ZIP)' }]} />
        <Button variant="primary" loading={create.isPending} onClick={() => create.mutate({ format: format as never, resource: resource as never })}>Request export</Button>
        {create.error && <span style={{ color: 'var(--coral)', fontSize: '0.84rem' }}>{(create.error as Error).message}</span>}
      </div>
      <DataTable caption="Export jobs" loading={exportsQ.isLoading} rows={exportsQ.data?.data} rowKey={(j) => j.id}
        empty={<p className={`${s.pad} ${s.muted}`}>No exports requested yet.</p>}
        columns={[
          { key: 'what', header: 'Export', cell: (j) => <span className={s.mono}>{String(j.params.resource)} · {String(j.params.format)}</span> },
          { key: 'st', header: 'Status', cell: (j) => <JobBadge status={j.status} /> },
          { key: 'when', header: 'Requested', cell: (j) => fmtAgo(j.created_at), hideBelow: 'md' },
          { key: 'size', header: 'Size', cell: (j) => (j.result?.size_bytes ? `${(Number(j.result.size_bytes) / 1024).toFixed(0)} KB · ${j.result.row_count} rows` : '—'), hideBelow: 'md' },
          { key: 'dl', header: '', align: 'right', cell: (j) => j.status === 'succeeded' ? <a href={`/api/v1/export-jobs/${j.id}/download`} className={s.row} style={{ justifyContent: 'flex-end', color: 'var(--accent-text)' }}><Download size={14} /> {String(j.result.filename)}</a> : j.error ? <span style={{ color: 'var(--coral)' }}>{j.error}</span> : null },
        ]} />
    </Panel>
  )
}

export default function ReportsPage() {
  return <Suspense><ReportsInner /></Suspense>
}
