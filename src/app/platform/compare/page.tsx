'use client'

import { Suspense, useState } from 'react'
import Link from 'next/link'
import { useRouter } from 'next/navigation'
import { X } from 'lucide-react'
import { ApiError } from '@/lib/api/client'
import { isAdmin, useMe } from '@/features/auth/api'
import { useComparisons, useCreateComparison } from '@/features/comparisons/api'
import { useComponents } from '@/features/components/api'
import { useSystems } from '@/features/design-systems/api'
import { Button, EmptyState, ErrorState, Field, fmtAgo, PageHeader, Panel, SearchInput, Tabs, Tag, Toggle } from '@/components/ui'
import s from '@/components/platform/page.module.scss'

type Kind = 'systems' | 'components'
const DIMS: Record<Kind, string[]> = {
  systems: ['overview', 'frameworks', 'tokens', 'accessibility', 'styling', 'governance', 'components', 'sources', 'maintenance'],
  components: ['overview', 'api', 'state', 'keyboard', 'accessibility', 'structure', 'evidence'],
}

function CompareInner() {
  const router = useRouter()
  const { data: me } = useMe()
  const saved = useComparisons()
  const create = useCreateComparison()
  const [kind, setKind] = useState<Kind>('components')
  const [q, setQ] = useState('')
  const [picked, setPicked] = useState<{ id: number; label: string }[]>([])
  const [dims, setDims] = useState<string[]>(DIMS.components)
  const [name, setName] = useState('')
  const sys = useSystems({ q, page_size: 8 })
  const comps = useComponents({ q, has_props: true, page_size: 8 }, kind === 'components')
  const options = kind === 'systems' ? sys.data?.data.map((x) => ({ id: x.id, label: x.name, sub: `${x.organization ?? ''} · ${x.source_count} sources` }))
    : comps.data?.data.map((x) => ({ id: x.id, label: `${x.name}`, sub: `${x.library} · ${x.props_count} props` }))
  const err = create.error instanceof ApiError ? create.error : null
  const canWrite = isAdmin(me)

  return (
    <>
      <PageHeader title="Comparison workspace" description="Comparisons are generated by the backend from persisted records. Every cell is labelled documented / not documented / not applicable; analytical notes are kept separate." />
      <div className={s.grid21}>
        <Panel title="New comparison">
          <div className={s.pad} style={{ display: 'grid', gap: 14 }}>
            <Tabs<Kind> value={kind} onChange={(k) => (setKind(k), setPicked([]), setDims(DIMS[k]))} tabs={[{ value: 'components', label: 'Components' }, { value: 'systems', label: 'Design systems' }]} />
            <SearchInput value={q} onChange={setQ} placeholder={kind === 'systems' ? 'Find design systems…' : 'Find components with documented APIs…'} />
            <ul className={s.list} style={{ border: '1px solid var(--line)', borderRadius: 10 }}>
              {options?.map((o) => {
                const on = picked.some((p) => p.id === o.id)
                return (
                  <li key={o.id} className={s.row} style={{ justifyContent: 'space-between' }}>
                    <span className={s.cell}><strong>{o.label}</strong><small>{o.sub}</small></span>
                    <Button size="sm" variant={on ? 'ghost' : 'secondary'} disabled={!on && picked.length >= 6} onClick={() => setPicked(on ? picked.filter((p) => p.id !== o.id) : [...picked, { id: o.id, label: `${o.label} (${o.sub.split(' · ')[0]})` }])}>{on ? 'Remove' : 'Add'}</Button>
                  </li>
                )
              })}
              {options?.length === 0 && <li className={s.muted}>No matches.</li>}
            </ul>
            <div>
              <p className={s.muted} style={{ fontSize: '0.8rem', marginBottom: 6 }}>Selected ({picked.length}/6, minimum 2)</p>
              <div className={s.row}>{picked.map((p) => <Tag key={p.id}>{p.label} <button aria-label={`Remove ${p.label}`} onClick={() => setPicked(picked.filter((x) => x.id !== p.id))} style={{ background: 'none', border: 0, color: 'inherit', cursor: 'pointer', display: 'grid' }}><X size={11} /></button></Tag>)}</div>
            </div>
            <div>
              <p className={s.muted} style={{ fontSize: '0.8rem', marginBottom: 4 }}>Dimensions</p>
              <div className={s.row}>{DIMS[kind].map((d) => <Toggle key={d} label={d} checked={dims.includes(d)} onChange={(v) => setDims(v ? [...dims, d] : dims.filter((x) => x !== d))} />)}</div>
            </div>
            <Field label="Name"><input value={name} onChange={(e) => setName(e.target.value)} maxLength={200} placeholder="e.g. Dialog APIs across headless libraries" /></Field>
            {err && <p role="alert" style={{ color: 'var(--coral)', fontSize: '0.86rem' }}>{err.message}</p>}
            <Button variant="primary" disabled={!canWrite || picked.length < 2 || dims.length === 0} loading={create.isPending}
              title={!canWrite ? 'Researcher role required' : undefined}
              onClick={() => create.mutate({ name: name.trim() || picked.map((p) => p.label).join(' vs '), kind, item_ids: picked.map((p) => p.id), dimensions: dims }, { onSuccess: (r) => router.push(`/platform/compare/${r.data.id}`) })}>
              Generate comparison
            </Button>
          </div>
        </Panel>
        <Panel title="Saved comparisons">
          {saved.error ? <ErrorState error={saved.error} /> : saved.data?.data.length === 0 ? <EmptyState title="No saved comparisons yet" /> : (
            <ul className={s.list}>
              {saved.data?.data.map((c) => (
                <li key={c.id}><Link href={`/platform/compare/${c.id}`} style={{ fontWeight: 500 }}>{c.name}</Link><div className={s.muted} style={{ fontSize: '0.78rem' }}>{c.kind} · {c.item_ids.length} items · {fmtAgo(c.updated_at)}</div></li>
              ))}
            </ul>
          )}
        </Panel>
      </div>
    </>
  )
}

export default function ComparePage() {
  return <Suspense><CompareInner /></Suspense>
}
